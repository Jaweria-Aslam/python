# User ki languages ki list
languages = ["Python", "Java", "Python", "C++", "Java"]

# List ko set mein convert karna
# Duplicate languages automatically remove ho jayengi
unique_languages = set(languages)

# len() se unique languages ki total quantity count karna
total_unique = len(unique_languages)

# Unique languages print karna
print("Unique Languages:", unique_languages)

# Total unique languages print karna
print("Total Unique Languages:", total_unique)